PRAGMA foreign_keys = ON;

CREATE TABLE SPORT (
  CodeSport TEXT PRIMARY KEY COLLATE NOCASE,
  LibelleSport TEXT NOT NULL COLLATE NOCASE
);
CREATE TABLE DIPLOME (
  CodeDiplome TEXT PRIMARY KEY COLLATE NOCASE,
  LibelleDiplome TEXT NOT NULL COLLATE NOCASE
);
CREATE TABLE ASSOCIATION (
  CodeAssoc TEXT PRIMARY KEY COLLATE NOCASE,
  NomAssoc TEXT NOT NULL COLLATE NOCASE,
  VilleAssoc TEXT NOT NULL COLLATE NOCASE
);
CREATE TABLE FORMATION (
  CodeFormation TEXT PRIMARY KEY COLLATE NOCASE,
  LibelleFormation TEXT NOT NULL COLLATE NOCASE,
  CodeSport TEXT NOT NULL COLLATE NOCASE REFERENCES SPORT(CodeSport),
  CodeDiplomeDelivre TEXT COLLATE NOCASE REFERENCES DIPLOME(CodeDiplome),
  CodeDiplomeNecessaire TEXT COLLATE NOCASE REFERENCES DIPLOME(CodeDiplome)
);
CREATE TABLE FORMATEUR (
  NumFormateur INTEGER PRIMARY KEY,
  NomFormateur TEXT NOT NULL COLLATE NOCASE,
  PrenomFormateur TEXT NOT NULL COLLATE NOCASE,
  VilleFormateur TEXT NOT NULL COLLATE NOCASE,
  TelFormateur TEXT,
  MailFormateur TEXT COLLATE NOCASE,
  CodeSport TEXT COLLATE NOCASE REFERENCES SPORT(CodeSport),
  CodeAssoc TEXT COLLATE NOCASE REFERENCES ASSOCIATION(CodeAssoc)
);
CREATE TABLE POSSEDER (
  NumFormateur INTEGER NOT NULL REFERENCES FORMATEUR(NumFormateur),
  CodeDiplome TEXT NOT NULL COLLATE NOCASE REFERENCES DIPLOME(CodeDiplome),
  PRIMARY KEY (NumFormateur, CodeDiplome)
);
CREATE TABLE SESSION_FORMATION (
  CodeFormation TEXT NOT NULL COLLATE NOCASE REFERENCES FORMATION(CodeFormation),
  NumSession INTEGER NOT NULL,
  Cout REAL NOT NULL CHECK (Cout > 0),
  DateDebut DATE NOT NULL,
  DateFin DATE NOT NULL,
  DateLimitIns DATE NOT NULL,
  Lieu TEXT NOT NULL COLLATE NOCASE,
  PRIMARY KEY (CodeFormation, NumSession),
  CHECK (DateFin >= DateDebut),
  CHECK (DateLimitIns <= DateDebut)
);
CREATE TABLE INTERVENIR (
  NumFormateur INTEGER NOT NULL REFERENCES FORMATEUR(NumFormateur),
  CodeFormation TEXT NOT NULL COLLATE NOCASE,
  NumSession INTEGER NOT NULL,
  NBH REAL NOT NULL CHECK (NBH > 0),
  PRIMARY KEY (NumFormateur, CodeFormation, NumSession),
  FOREIGN KEY (CodeFormation, NumSession) REFERENCES SESSION_FORMATION(CodeFormation, NumSession)
);

