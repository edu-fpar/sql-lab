PRAGMA foreign_keys = ON;

CREATE TABLE AGENCE (
  CodeAgence TEXT PRIMARY KEY COLLATE NOCASE,
  NomAgence TEXT NOT NULL COLLATE NOCASE,
  RueAgence TEXT COLLATE NOCASE,
  VilleAgence TEXT NOT NULL COLLATE NOCASE
);
CREATE TABLE PERSONNEL (
  CodePersonnel INTEGER PRIMARY KEY,
  NomPersonnel TEXT NOT NULL COLLATE NOCASE,
  PrenomPersonnel TEXT NOT NULL COLLATE NOCASE,
  TelPersonnel TEXT COLLATE NOCASE,
  MailPersonnel TEXT COLLATE NOCASE,
  TypePersonnel TEXT NOT NULL COLLATE NOCASE
    CHECK (TypePersonnel IN ('Agence', 'Intervenant')),
  CodeAgence TEXT COLLATE NOCASE REFERENCES AGENCE(CodeAgence),
  CHECK ((TypePersonnel = 'Agence' AND CodeAgence IS NOT NULL)
      OR (TypePersonnel = 'Intervenant' AND CodeAgence IS NULL))
);
CREATE TABLE TYPE_MATERIEL (
  CodeTypeMateriel TEXT PRIMARY KEY COLLATE NOCASE,
  NomTypeMateriel TEXT NOT NULL COLLATE NOCASE
);
CREATE TABLE MATERIEL (
  CodeMateriel TEXT PRIMARY KEY COLLATE NOCASE,
  NomMateriel TEXT NOT NULL COLLATE NOCASE,
  CodeTypeMateriel TEXT NOT NULL COLLATE NOCASE REFERENCES TYPE_MATERIEL(CodeTypeMateriel)
);
CREATE TABLE DEMANDE (
  NoDemande TEXT PRIMARY KEY COLLATE NOCASE,
  MotifDemande TEXT NOT NULL COLLATE NOCASE,
  DateDemande DATE NOT NULL,
  DelaiDemande INTEGER NOT NULL CHECK (DelaiDemande > 0),
  EtatDemande TEXT NOT NULL COLLATE NOCASE
    CHECK (EtatDemande IN ('En attente', 'En cours', 'Terminée')),
  CodeMateriel TEXT NOT NULL COLLATE NOCASE REFERENCES MATERIEL(CodeMateriel),
  CodePersonnel INTEGER NOT NULL REFERENCES PERSONNEL(CodePersonnel)
);
CREATE TABLE INTERVENTION (
  NoDemande TEXT NOT NULL COLLATE NOCASE REFERENCES DEMANDE(NoDemande),
  CodePersonnelInt INTEGER NOT NULL REFERENCES PERSONNEL(CodePersonnel),
  DateIntervention DATE NOT NULL,
  Nbh REAL NOT NULL CHECK (Nbh > 0),
  PRIMARY KEY (NoDemande, CodePersonnelInt)
);
CREATE TABLE SUIVI (
  NoDemande TEXT NOT NULL COLLATE NOCASE REFERENCES DEMANDE(NoDemande),
  NoSuivi INTEGER NOT NULL,
  DescriptifSuivi TEXT NOT NULL COLLATE NOCASE,
  PRIMARY KEY (NoDemande, NoSuivi)
);

