PRAGMA foreign_keys = ON;

CREATE TABLE ENTREPOT (
  CodeEnt TEXT PRIMARY KEY COLLATE NOCASE,
  AdresseVilleEnt TEXT NOT NULL COLLATE NOCASE,
  Surface INTEGER NOT NULL CHECK (Surface > 0)
);
CREATE TABLE SALARIE (
  NumSal INTEGER PRIMARY KEY,
  NomSal TEXT NOT NULL COLLATE NOCASE,
  PrenomSal TEXT NOT NULL COLLATE NOCASE,
  DateNaissSal DATE NOT NULL
);
CREATE TABLE CHAUFFEUR (
  NumSal INTEGER PRIMARY KEY REFERENCES SALARIE(NumSal),
  NumPermisPL TEXT NOT NULL COLLATE NOCASE,
  DateObtention DATE NOT NULL,
  DateDernVisitMed DATE NOT NULL
);
CREATE TABLE MANUTENTIONNAIRE (
  NumSal INTEGER PRIMARY KEY REFERENCES SALARIE(NumSal),
  NumCACES TEXT NOT NULL COLLATE NOCASE,
  CodeEnt TEXT NOT NULL COLLATE NOCASE REFERENCES ENTREPOT(CodeEnt),
  NumSalChef INTEGER REFERENCES MANUTENTIONNAIRE(NumSal),
  CHECK (NumSalChef IS NULL OR NumSalChef <> NumSal)
);
CREATE TABLE VEHICULE (
  NumImmat TEXT PRIMARY KEY COLLATE NOCASE,
  NbEssieu INTEGER NOT NULL CHECK (NbEssieu BETWEEN 2 AND 6),
  Volume INTEGER NOT NULL CHECK (Volume > 0),
  PTRA REAL NOT NULL CHECK (PTRA > 0)
);
CREATE TABLE TOURNEE (
  CodeTourn TEXT PRIMARY KEY COLLATE NOCASE,
  DureeEstim REAL NOT NULL CHECK (DureeEstim > 0),
  NbKMTheor INTEGER NOT NULL CHECK (NbKMTheor > 0),
  CodeEnt TEXT NOT NULL COLLATE NOCASE REFERENCES ENTREPOT(CodeEnt)
);
CREATE TABLE PDL (
  CodePDL TEXT PRIMARY KEY COLLATE NOCASE,
  RaisonSociale TEXT NOT NULL COLLATE NOCASE,
  AdresseVillePDL TEXT NOT NULL COLLATE NOCASE,
  GPSLatPDL REAL,
  GPSLongPDL REAL
);
CREATE TABLE TOURNEE_PDL (
  CodeTourn TEXT NOT NULL COLLATE NOCASE REFERENCES TOURNEE(CodeTourn),
  CodePDL TEXT NOT NULL COLLATE NOCASE REFERENCES PDL(CodePDL),
  OrdrePassage INTEGER NOT NULL CHECK (OrdrePassage > 0),
  PRIMARY KEY (CodeTourn, CodePDL)
);
CREATE TABLE AFFECTER (
  NumSal INTEGER NOT NULL REFERENCES CHAUFFEUR(NumSal),
  DateJour DATE NOT NULL,
  NumImmat TEXT NOT NULL COLLATE NOCASE REFERENCES VEHICULE(NumImmat),
  PRIMARY KEY (NumSal, DateJour)
);
CREATE TABLE EFFECTUER (
  NumSal INTEGER NOT NULL REFERENCES CHAUFFEUR(NumSal),
  DateJour DATE NOT NULL,
  CodeTourn TEXT NOT NULL COLLATE NOCASE REFERENCES TOURNEE(CodeTourn),
  PRIMARY KEY (NumSal, DateJour, CodeTourn)
);

