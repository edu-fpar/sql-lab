CREATE TABLE EMPLOYE (
  CodeEmp INTEGER PRIMARY KEY,
  NomEmp TEXT NOT NULL COLLATE NOCASE,
  PrenomEmp TEXT NOT NULL COLLATE NOCASE,
  Salaire REAL NOT NULL,
  StatutEmp TEXT NOT NULL COLLATE NOCASE CHECK (StatutEmp IN ('Permanent', 'Saisonnier')),
  NumSecteur INTEGER NOT NULL,
  NumHotel INTEGER NOT NULL,
  FOREIGN KEY (NumSecteur, NumHotel) REFERENCES CONCERNER(NumSecteur, NumHotel)
);
CREATE TABLE TYPE_LODGE (
  CodeType INTEGER PRIMARY KEY,
  LibelleType TEXT NOT NULL COLLATE NOCASE,
  TarifSemaine REAL NOT NULL,
  TarifNuitee REAL NOT NULL
);
CREATE TABLE LODGE (
  NumLodge INTEGER NOT NULL,
  NumHotel INTEGER NOT NULL REFERENCES HOTEL(NumHotel),
  NomLodge TEXT NOT NULL COLLATE NOCASE,
  CapaciteAccueil INTEGER NOT NULL,
  NbPieces INTEGER NOT NULL,
  Surface REAL NOT NULL,
  CodeType INTEGER NOT NULL REFERENCES TYPE_LODGE(CodeType),
  PRIMARY KEY (NumLodge, NumHotel)
);

