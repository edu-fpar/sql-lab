CREATE TABLE HOTEL (
  NumHotel INTEGER PRIMARY KEY,
  NomHotel TEXT NOT NULL COLLATE NOCASE,
  DateCreation DATE NOT NULL,
  AdRueHotel TEXT COLLATE NOCASE,
  CPHotel TEXT NOT NULL,
  VilleHotel TEXT NOT NULL COLLATE NOCASE,
  TelHotel TEXT,
  NomRespHotel TEXT COLLATE NOCASE,
  CategorieHotel INTEGER NOT NULL CHECK (CategorieHotel BETWEEN 1 AND 5)
);
CREATE TABLE TYPECHAMBRE (
  NumType INTEGER PRIMARY KEY,
  LibelleType TEXT NOT NULL COLLATE NOCASE,
  Fumeur TEXT NOT NULL COLLATE NOCASE CHECK (Fumeur IN ('O', 'N'))
);
CREATE TABLE PERIODE (
  NumPeriode INTEGER PRIMARY KEY,
  LibellePeriode TEXT NOT NULL COLLATE NOCASE
);
CREATE TABLE TARIF (
  NumType INTEGER NOT NULL REFERENCES TYPECHAMBRE(NumType),
  NumHotel INTEGER NOT NULL REFERENCES HOTEL(NumHotel),
  PrixHT REAL NOT NULL CHECK (PrixHT > 0),
  NbChambreTyp INTEGER NOT NULL CHECK (NbChambreTyp > 0),
  PRIMARY KEY (NumType, NumHotel)
);
CREATE TABLE REDUCTION (
  NumHotel INTEGER NOT NULL REFERENCES HOTEL(NumHotel),
  NumPeriode INTEGER NOT NULL REFERENCES PERIODE(NumPeriode),
  NumType INTEGER NOT NULL REFERENCES TYPECHAMBRE(NumType),
  TxReduction REAL NOT NULL CHECK (TxReduction >= 0 AND TxReduction < 100),
  PRIMARY KEY (NumHotel, NumPeriode, NumType)
);
CREATE TABLE CLIENT (
  NumCli INTEGER PRIMARY KEY,
  NomCli TEXT NOT NULL COLLATE NOCASE,
  PrenomCli TEXT NOT NULL COLLATE NOCASE,
  CPCli TEXT,
  VilleCli TEXT COLLATE NOCASE,
  MelCli TEXT COLLATE NOCASE,
  TelCli TEXT
);
CREATE TABLE RESERVATION (
  NumRes INTEGER PRIMARY KEY,
  NbChambreRes INTEGER NOT NULL CHECK (NbChambreRes >= 1),
  NbNuitRes INTEGER NOT NULL CHECK (NbNuitRes >= 1),
  DateDebRes DATE NOT NULL,
  DateFinRes DATE NOT NULL,
  AnnuleRes TEXT NOT NULL COLLATE NOCASE CHECK (AnnuleRes IN ('O', 'N')),
  NumCli INTEGER NOT NULL REFERENCES CLIENT(NumCli),
  NumHotel INTEGER NOT NULL REFERENCES HOTEL(NumHotel)
);
CREATE TABLE FACTURE (
  NumFac INTEGER PRIMARY KEY,
  DateFac DATE NOT NULL,
  PayeFac TEXT NOT NULL COLLATE NOCASE CHECK (PayeFac IN ('O', 'N')),
  NumRes INTEGER NOT NULL REFERENCES RESERVATION(NumRes)
);

