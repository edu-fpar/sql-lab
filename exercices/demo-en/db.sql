-- Date of the day (simulated): 2025-06-15

PRAGMA foreign_keys = ON;

CREATE TABLE CATEGORY (
  CategoryId INTEGER PRIMARY KEY,
  CategoryName TEXT NOT NULL COLLATE NOCASE,
  DailyRate REAL NOT NULL
);
CREATE TABLE STORE (
  StoreId INTEGER PRIMARY KEY,
  StoreName TEXT NOT NULL COLLATE NOCASE,
  City TEXT NOT NULL COLLATE NOCASE,
  Phone TEXT
);
CREATE TABLE BIKE (
  BikeId INTEGER PRIMARY KEY,
  Model TEXT NOT NULL COLLATE NOCASE,
  Brand TEXT NOT NULL COLLATE NOCASE,
  PurchaseDate DATE NOT NULL,
  FrameSize TEXT CHECK (FrameSize IN ('S', 'M', 'L')),
  CategoryId INTEGER NOT NULL REFERENCES CATEGORY(CategoryId),
  StoreId INTEGER NOT NULL REFERENCES STORE(StoreId)
);
CREATE TABLE CUSTOMER (
  CustomerId INTEGER PRIMARY KEY,
  LastName TEXT NOT NULL COLLATE NOCASE,
  FirstName TEXT NOT NULL COLLATE NOCASE,
  City TEXT COLLATE NOCASE,
  Email TEXT COLLATE NOCASE,
  Phone TEXT,
  RegistrationDate DATE NOT NULL,
  ReferredBy INTEGER REFERENCES CUSTOMER(CustomerId)
);
CREATE TABLE RENTAL (
  RentalId INTEGER PRIMARY KEY,
  StartDate DATE NOT NULL,
  ReturnDate DATE,
  CustomerId INTEGER NOT NULL REFERENCES CUSTOMER(CustomerId),
  StoreId INTEGER NOT NULL REFERENCES STORE(StoreId)
);
CREATE TABLE RENTAL_LINE (
  RentalId INTEGER NOT NULL REFERENCES RENTAL(RentalId),
  BikeId INTEGER NOT NULL REFERENCES BIKE(BikeId),
  DailyPrice REAL NOT NULL,
  PRIMARY KEY (RentalId, BikeId)
);

