PRAGMA foreign_keys = ON;

CREATE TABLE TYPE_DECHETS (
  idTypeDechets INTEGER PRIMARY KEY,
  libelleTypeDechets TEXT NOT NULL COLLATE NOCASE,
  contientDonnees TEXT NOT NULL CHECK (contientDonnees IN ('O', 'N'))
);
CREATE TABLE TYPE_ABONNEMENT (
  idTypeAbo INTEGER PRIMARY KEY,
  libelleTypeAbo TEXT NOT NULL COLLATE NOCASE,
  tarifAbo REAL NOT NULL
);
CREATE TABLE CONCERNER (
  idTypeDechets INTEGER NOT NULL REFERENCES TYPE_DECHETS(idTypeDechets),
  idTypeAbo INTEGER NOT NULL REFERENCES TYPE_ABONNEMENT(idTypeAbo),
  PRIMARY KEY (idTypeDechets, idTypeAbo)
);
CREATE TABLE CLIENT (
  idCli INTEGER PRIMARY KEY,
  nomCli TEXT NOT NULL COLLATE NOCASE,
  rueCli TEXT COLLATE NOCASE,
  villeCli TEXT COLLATE NOCASE,
  telCli TEXT,
  courrielCli TEXT COLLATE NOCASE
);
CREATE TABLE ABONNEMENT (
  idAbo INTEGER PRIMARY KEY,
  frequenceCollecte TEXT NOT NULL COLLATE NOCASE
    CHECK (frequenceCollecte IN ('Mensuelle', 'Bimestrielle', 'Trimestrielle', 'Semestrielle')),
  idTypeAbo INTEGER NOT NULL REFERENCES TYPE_ABONNEMENT(idTypeAbo),
  idCli INTEGER NOT NULL REFERENCES CLIENT(idCli)
);
CREATE TABLE COLLECTE (
  idCollecte INTEGER NOT NULL,
  idAbo INTEGER NOT NULL REFERENCES ABONNEMENT(idAbo),
  dateCollecte DATE NOT NULL,
  PRIMARY KEY (idCollecte, idAbo)
);
CREATE TABLE DETAIL_COLLECTE (
  idCollecte INTEGER NOT NULL,
  idAbo INTEGER NOT NULL,
  idTypeDechets INTEGER NOT NULL REFERENCES TYPE_DECHETS(idTypeDechets),
  poidsCollecte REAL NOT NULL CHECK (poidsCollecte > 0),
  PRIMARY KEY (idCollecte, idAbo, idTypeDechets),
  FOREIGN KEY (idCollecte, idAbo) REFERENCES COLLECTE(idCollecte, idAbo)
);

