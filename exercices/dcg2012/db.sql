PRAGMA foreign_keys = ON;

CREATE TABLE SALARIE (
  Matricule INTEGER PRIMARY KEY,
  Nom TEXT NOT NULL COLLATE NOCASE,
  Prenom TEXT NOT NULL COLLATE NOCASE,
  Qualification TEXT NOT NULL COLLATE NOCASE,
  Niveau INTEGER NOT NULL CHECK (Niveau BETWEEN 1 AND 4),
  DateEntree DATE NOT NULL,
  DateSortie DATE,
  CHECK (DateSortie IS NULL OR DateSortie >= DateEntree)
);
CREATE TABLE ARCHIVE_SALARIE (
  Matricule INTEGER PRIMARY KEY,
  Nom TEXT NOT NULL COLLATE NOCASE,
  Prenom TEXT NOT NULL COLLATE NOCASE,
  Qualification TEXT NOT NULL COLLATE NOCASE,
  Niveau INTEGER NOT NULL,
  DateEntree DATE NOT NULL,
  DateSortie DATE
);
CREATE TABLE CLIENT (
  NumCli INTEGER PRIMARY KEY,
  TypeClient TEXT NOT NULL COLLATE NOCASE CHECK (TypeClient IN ('Particulier', 'Entreprise')),
  NomCli TEXT NOT NULL COLLATE NOCASE,
  PrenomCli TEXT COLLATE NOCASE,
  NumSiret TEXT,
  AdresseCli TEXT NOT NULL COLLATE NOCASE,
  CodePostalCli TEXT NOT NULL,
  VilleCli TEXT NOT NULL COLLATE NOCASE,
  TelCli TEXT
);
CREATE TABLE CHANTIER (
  NumChantier TEXT PRIMARY KEY COLLATE NOCASE,
  AdresseChantier TEXT NOT NULL COLLATE NOCASE,
  VilleChantier TEXT NOT NULL COLLATE NOCASE,
  NumCli INTEGER NOT NULL REFERENCES CLIENT(NumCli),
  MatriculeEncadrant INTEGER NOT NULL REFERENCES SALARIE(Matricule)
);
CREATE TABLE CATEGORIE_TACHE (
  NumCategorie INTEGER PRIMARY KEY,
  Designation TEXT NOT NULL COLLATE NOCASE
);
CREATE TABLE TACHE (
  NumChantier TEXT NOT NULL COLLATE NOCASE REFERENCES CHANTIER(NumChantier),
  NumTache TEXT NOT NULL COLLATE NOCASE,
  Description TEXT NOT NULL COLLATE NOCASE,
  DateDebutPrevue DATE NOT NULL,
  DureePrevue INTEGER NOT NULL CHECK (DureePrevue > 0),
  DateDebutReelle DATE,
  DateFinReelle DATE,
  NumCategorie INTEGER NOT NULL REFERENCES CATEGORIE_TACHE(NumCategorie),
  PRIMARY KEY (NumChantier, NumTache)
);
CREATE TABLE AFFECTER (
  Matricule INTEGER NOT NULL REFERENCES SALARIE(Matricule),
  NumChantier TEXT NOT NULL COLLATE NOCASE,
  NumTache TEXT NOT NULL COLLATE NOCASE,
  Duree REAL NOT NULL CHECK (Duree > 0),
  PRIMARY KEY (Matricule, NumChantier, NumTache),
  FOREIGN KEY (NumChantier, NumTache) REFERENCES TACHE(NumChantier, NumTache)
);
CREATE TABLE EFFECTUER (
  Matricule INTEGER NOT NULL REFERENCES SALARIE(Matricule),
  NumChantier TEXT NOT NULL COLLATE NOCASE,
  NumTache TEXT NOT NULL COLLATE NOCASE,
  DateTravail DATE NOT NULL,
  NombreHeures REAL NOT NULL CHECK (NombreHeures > 0 AND NombreHeures <= 12),
  PRIMARY KEY (Matricule, NumChantier, NumTache, DateTravail),
  FOREIGN KEY (NumChantier, NumTache) REFERENCES TACHE(NumChantier, NumTache)
);

