PRAGMA foreign_keys = ON;

CREATE TABLE CATEGORIA (
  IdCategoria INTEGER PRIMARY KEY,
  NombreCategoria TEXT NOT NULL COLLATE NOCASE,
  TarifaDiaria REAL NOT NULL
);
CREATE TABLE TIENDA (
  IdTienda INTEGER PRIMARY KEY,
  NombreTienda TEXT NOT NULL COLLATE NOCASE,
  Ciudad TEXT NOT NULL COLLATE NOCASE,
  Telefono TEXT
);
CREATE TABLE BICICLETA (
  IdBicicleta INTEGER PRIMARY KEY,
  Modelo TEXT NOT NULL COLLATE NOCASE,
  Marca TEXT NOT NULL COLLATE NOCASE,
  FechaCompra DATE NOT NULL,
  TallaCuadro TEXT CHECK (TallaCuadro IN ('S', 'M', 'L')),
  IdCategoria INTEGER NOT NULL REFERENCES CATEGORIA(IdCategoria),
  IdTienda INTEGER NOT NULL REFERENCES TIENDA(IdTienda)
);
CREATE TABLE CLIENTE (
  IdCliente INTEGER PRIMARY KEY,
  Apellido TEXT NOT NULL COLLATE NOCASE,
  Nombre TEXT NOT NULL COLLATE NOCASE,
  Ciudad TEXT COLLATE NOCASE,
  Email TEXT COLLATE NOCASE,
  Telefono TEXT,
  FechaAlta DATE NOT NULL,
  RecomendadoPor INTEGER REFERENCES CLIENTE(IdCliente)
);
CREATE TABLE ALQUILER (
  IdAlquiler INTEGER PRIMARY KEY,
  FechaInicio DATE NOT NULL,
  FechaDevolucion DATE,
  IdCliente INTEGER NOT NULL REFERENCES CLIENTE(IdCliente),
  IdTienda INTEGER NOT NULL REFERENCES TIENDA(IdTienda)
);
CREATE TABLE LINEA_ALQUILER (
  IdAlquiler INTEGER NOT NULL REFERENCES ALQUILER(IdAlquiler),
  IdBicicleta INTEGER NOT NULL REFERENCES BICICLETA(IdBicicleta),
  PrecioDiario REAL NOT NULL,
  PRIMARY KEY (IdAlquiler, IdBicicleta)
);

