PRAGMA foreign_keys = ON;

CREATE TABLE AGENCE (
  NumAgence INTEGER PRIMARY KEY,
  NomAgence TEXT NOT NULL COLLATE NOCASE,
  AdresseAgence TEXT COLLATE NOCASE,
  VilleAgence TEXT NOT NULL COLLATE NOCASE,
  CPAgence TEXT NOT NULL
);
CREATE TABLE CLIENT (
  NumClient INTEGER PRIMARY KEY,
  NomClient TEXT NOT NULL COLLATE NOCASE,
  CPClient TEXT,
  VilleClient TEXT COLLATE NOCASE
);
CREATE TABLE CATEGORIE (
  NumCategorie INTEGER PRIMARY KEY,
  NomCategorie TEXT NOT NULL COLLATE NOCASE,
  TarifKm REAL NOT NULL CHECK (TarifKm > 0)
);
CREATE TABLE VEHICULE (
  NumVeh INTEGER PRIMARY KEY,
  Immatriculation TEXT NOT NULL UNIQUE COLLATE NOCASE,
  Modele TEXT NOT NULL COLLATE NOCASE,
  DateAchat DATE NOT NULL,
  Capacite INTEGER NOT NULL CHECK (Capacite > 0),
  MontantCaution REAL NOT NULL CHECK (MontantCaution >= 0),
  TypeLocation TEXT NOT NULL COLLATE NOCASE
    CHECK (TypeLocation IN ('Avec chauffeur', 'Sans chauffeur')),
  ForfaitJour REAL CHECK (ForfaitJour > 0),
  NumCategorie INTEGER REFERENCES CATEGORIE(NumCategorie),
  CHECK ((TypeLocation = 'Avec chauffeur' AND ForfaitJour IS NOT NULL AND NumCategorie IS NULL)
      OR (TypeLocation = 'Sans chauffeur' AND ForfaitJour IS NULL AND NumCategorie IS NOT NULL))
);
CREATE TABLE CONTRAT (
  NumAgence INTEGER NOT NULL REFERENCES AGENCE(NumAgence),
  NumContrat INTEGER NOT NULL,
  DateContrat DATE NOT NULL,
  DateDebut DATE NOT NULL,
  DateFin DATE NOT NULL,
  KmsRemise INTEGER,
  KmsRetour INTEGER,
  NumClient INTEGER NOT NULL REFERENCES CLIENT(NumClient),
  NumVeh INTEGER NOT NULL REFERENCES VEHICULE(NumVeh),
  PRIMARY KEY (NumAgence, NumContrat),
  CHECK (DateContrat <= DateDebut AND DateDebut <= DateFin),
  CHECK (KmsRetour IS NULL OR KmsRetour >= KmsRemise)
);
CREATE TABLE CONTENTIEUX (
  NumAgence INTEGER NOT NULL,
  NumContrat INTEGER NOT NULL,
  NumDossier INTEGER NOT NULL,
  DateOuverture DATE NOT NULL,
  DateCloture DATE,
  PRIMARY KEY (NumAgence, NumContrat, NumDossier),
  FOREIGN KEY (NumAgence, NumContrat) REFERENCES CONTRAT(NumAgence, NumContrat)
);
CREATE TABLE LITIGES_ANCIENS (
  NumAgence INTEGER NOT NULL,
  NumContrat INTEGER NOT NULL,
  NumDossier INTEGER NOT NULL,
  DateOuverture DATE NOT NULL,
  DateCloture DATE,
  PRIMARY KEY (NumAgence, NumContrat, NumDossier),
  FOREIGN KEY (NumAgence, NumContrat) REFERENCES CONTRAT(NumAgence, NumContrat)
);

