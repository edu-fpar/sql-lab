  GradeInstructeur TEXT COLLATE NOCASE,
  Diplome TEXT COLLATE NOCASE
);
CREATE TABLE AVOIR (
  CodeAffiliation INTEGER NOT NULL REFERENCES CLUB(CodeAffiliation),
  CodeInstructeur INTEGER NOT NULL REFERENCES INSTRUCTEUR(CodeInstructeur),
  PRIMARY KEY (CodeAffiliation, CodeInstructeur)
);
CREATE TABLE SALLE (
  CodeSalle INTEGER PRIMARY KEY,
  LieuSalle TEXT NOT NULL COLLATE NOCASE
);
CREATE TABLE DISPOSER (
  CodeAffiliation INTEGER NOT NULL REFERENCES CLUB(CodeAffiliation),
  CodeSalle INTEGER NOT NULL REFERENCES SALLE(CodeSalle),
