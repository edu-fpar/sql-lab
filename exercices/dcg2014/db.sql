CREATE TABLE COMPRENDRE (
  CodeAffiliation INTEGER NOT NULL REFERENCES CLUB(CodeAffiliation),
  NumeroLicence INTEGER NOT NULL REFERENCES ADHERENT(NumeroLicence),
  DateAdhesion DATE NOT NULL,
  PRIMARY KEY (CodeAffiliation, NumeroLicence)
);
CREATE TABLE INSTRUCTEUR (
  CodeInstructeur INTEGER PRIMARY KEY,
  NomInstructeur TEXT NOT NULL COLLATE NOCASE,
  PrenomInstructeur TEXT NOT NULL COLLATE NOCASE,
  TypeInstructeur TEXT NOT NULL COLLATE NOCASE
